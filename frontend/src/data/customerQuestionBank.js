/**
 * Get the initial 3-5 recommended questions based on context.
 * If there is a flagged / under-review transaction, prioritize recognition and explanation.
 */
export function getRecommendedQuestions(context = {}) {
  const { hasFlaggedTx = false, hasPendingApproval = false } = context

  if (hasFlaggedTx || hasPendingApproval) {
    return [
      MASTER_QUESTION_BANK.find((q) => q.id === 'fa_flagged_why'),
      MASTER_QUESTION_BANK.find((q) => q.id === 'act_summarize'),
      MASTER_QUESTION_BANK.find((q) => q.id === 'sec_account_safe'),
      MASTER_QUESTION_BANK.find((q) => q.id === 'fa_next_step'),
    ].filter(Boolean)
  }

  return [
    MASTER_QUESTION_BANK.find((q) => q.id === 'tx_recent'),
    MASTER_QUESTION_BANK.find((q) => q.id === 'sec_account_safe'),
    MASTER_QUESTION_BANK.find((q) => q.id === 'act_summarize'),
    MASTER_QUESTION_BANK.find((q) => q.id === 'hlp_how_help'),
  ].filter(Boolean)
}
